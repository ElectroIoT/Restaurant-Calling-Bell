"""One-off: derive gen_schematic.py from the NewYearPixelFireworks generator (kept for provenance)."""
src = open(r"D:\My Project\ElectroIoT\NewYearPixelFireworks\tools\gen_schematic.py", encoding="utf-8").read()


def rep(a, b):
    global src
    assert a in src, a[:70]
    src = src.replace(a, b)


rep('"""Generate hardware/kicad/nypf-base.kicad_sch from design.py (every pin gets a stub + net label/power symbol)."""',
    '"""Generate <board>/kicad/<project>.kicad_sch from <board>_design.py (every pin gets a stub + net label/power symbol).\n\n'
    'Usage: python gen_schematic.py remote|receiver   (adapted from the NewYearPixelFireworks generator)\n"""')
rep('_D = importlib.import_module(os.environ.get("NYPF_DESIGN", "design"))', '_D = importlib.import_module(sys.argv[1] + "_design")')
rep('POWER_NETS = {"GND": "GND", "+5V": "+5V", "+3V3": "+3V3"}', 'POWER_NETS = {"GND": "GND", "+5V": "+5V", "+3V3": "+3V3", "+3V0": "+3V0"}')
rep('TITLE = getattr(_D, "TITLE", "New Year Pixel Fireworks 2027 - Base controller")', 'TITLE = _D.TITLE\nCOMMENT = getattr(_D, "COMMENT", "")')
rep('OUT = os.path.join(os.path.dirname(__file__), "..", "hardware", getattr(_D, "OUT_DIR", "kicad"), PROJECT + ".kicad_sch")',
    'OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", _D.OUT_DIR, PROJECT + ".kicad_sch")')
rep('(comment 1 "ESP32-S3 + 74AHCT541 level shifter + USB-C 5V") (comment 2 "Generated by tools/gen_schematic.py from tools/design.py"))',
    '(comment 1 "%s") (comment 2 "Generated by hardware/tools/gen_schematic.py from %s_design.py"))')
rep('% (ROOT, paper, TITLE, libs,', '% (ROOT, paper, TITLE, COMMENT, sys.argv[1], libs,')
rep('(date "2026-10-21")', '(date "2026-10-29")')
open(r"D:\My Project\ElectroIoT\restaurant-calling-bell\hardware\tools\gen_schematic.py", "w", encoding="utf-8").write(src)
